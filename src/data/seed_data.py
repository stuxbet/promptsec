def email(
    item_id: str,
    trust: TrustLevel,
    sensitivity: SensitivityLevel,
    tags: list[str],
    content: str,
    expected_behavior: ExpectedBehavior,
    attack_goal: str | None = None,
) -> ContentItem:
    return ContentItem(
        id=item_id,
        type=ContentType.EMAIL,
        trust_level=trust,
        sensitivity=sensitivity,
        content=content,
        tags=tags,
        expected_behavior=expected_behavior,
        attack_goal=attack_goal,
    )


def doc(
    item_id: str,
    trust: TrustLevel,
    sensitivity: SensitivityLevel,
    tags: list[str],
    content: str,
    expected_behavior: ExpectedBehavior,
    attack_goal: str | None = None,
) -> ContentItem:
    return ContentItem(
        id=item_id,
        type=ContentType.DOC,
        trust_level=trust,
        sensitivity=sensitivity,
        content=content,
        tags=tags,
        expected_behavior=expected_behavior,
        attack_goal=attack_goal,
    )


def scenario(
    scenario_id: str,
    user_request: str,
    relevant_data_files: list[str],
    expected_safe_behavior: ExpectedBehavior,
    unsafe_behavior_to_avoid: str,
    attack_category: ScenarioCategory,
    sensitivity_level: SensitivityLevel,
) -> Scenario:
    return Scenario(
        scenario_id=scenario_id,
        user_request=user_request,
        relevant_data_files=relevant_data_files,
        expected_safe_behavior=expected_safe_behavior,
        unsafe_behavior_to_avoid=unsafe_behavior_to_avoid,
        attack_category=attack_category,
        sensitivity_level=sensitivity_level,
    )


def content_path(item: ContentItem) -> str:
    folder = "emails" if item.type == ContentType.EMAIL else "docs"
    return f"{folder}/{item.id}.json"


