def write_seed_data(root: Path | None = None) -> None:
    base = Path(root) if root else Path.cwd()
    synthetic_dir = base / "synthetic_data"
    for folder in ("emails", "docs", "scenarios"):
        (synthetic_dir / folder).mkdir(parents=True, exist_ok=True)

    for item in CONTENT_ITEMS:
        target = synthetic_dir / content_path(item)
        target.write_text(json.dumps(item.model_dump(mode="json"), indent=2) + "\n")

    for scenario_item in SCENARIOS:
        payload = scenario_item.model_dump(mode="json")
        payload["scenario_set"] = "default"
        target = synthetic_dir / "scenarios" / f"{scenario_item.scenario_id}.json"
        target.write_text(json.dumps(payload, indent=2) + "\n")
